#!/usr/bin/env node
/**
 * Bundles drizzle-kit's generated migrations into a single TypeScript
 * module (src/db/migrations/bundle.ts).
 *
 * Why: drizzle-kit generates `migrations.js`, which does
 * `import sql from './0000_init.sql'`. Under Metro/Hermes that resolves to
 * a numeric asset ID rather than the SQL text, which the drizzle migrator
 * cannot execute. Inlining the SQL keeps runtime behaviour identical on
 * device, in Jest and in plain Node.
 *
 * Run automatically after `npm run db:generate`.
 */

import fs from 'node:fs';
import path from 'node:path';
import url from 'node:url';

const here = path.dirname(url.fileURLToPath(import.meta.url));
const migrationsDir = path.join(here, '..', 'src', 'db', 'migrations');

const journalPath = path.join(migrationsDir, 'meta', '_journal.json');
if (!fs.existsSync(journalPath)) {
  console.error(`No migration journal found at ${journalPath}`);
  process.exit(1);
}

const journal = JSON.parse(fs.readFileSync(journalPath, 'utf8'));

const entries = journal.entries.map((entry) => {
  const sqlPath = path.join(migrationsDir, `${entry.tag}.sql`);
  const sql = fs.readFileSync(sqlPath, 'utf8');
  const key = `m${String(entry.idx).padStart(4, '0')}`;
  return { key, entry, sql };
});

const out = `// AUTO-GENERATED by tools/build-migrations.mjs — do not edit.
// Source of truth: drizzle-kit output in this folder (${migrationsDir}).

export interface MigrationJournalEntry {
  idx: number;
  version: string;
  when: number;
  tag: string;
  breakpoints: boolean;
}

interface MigrationBundle {
  journal: { entries: MigrationJournalEntry[] };
  migrations: Record<string, string>;
}

const journal = ${JSON.stringify(journal, null, 2)};

const migrations: Record<string, string> = {
${entries.map(({ key, sql }) => `  ${key}: ${JSON.stringify(sql)},`).join('\n')}
};

export default { journal, migrations } satisfies MigrationBundle;
`;

const outPath = path.join(migrationsDir, 'bundle.ts');
fs.writeFileSync(outPath, out);
console.log(`Wrote ${outPath} (${entries.length} migration(s))`);
